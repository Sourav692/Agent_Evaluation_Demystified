#!/usr/bin/env python3
"""Regenerate a profile's references/checks.md from its data/checks.json and a
recorded audit: the latest line of --history when given, else the profile's
bundled baseline (if it has one), else none (empty Last audit columns).

Run after adding or editing a check in data/checks.json so the readable
catalogue stays in step with the one the scripts use:

  python3 render_checks.py --profile fde
  python3 render_checks.py --profile eval --history .website_spec/site-audits/history.jsonl
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
PROFILES = SKILL / "profiles"


def cell(text: str) -> str:
    return str(text).replace("|", "/").replace("\n", " ")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", required=True, help="site profile: a folder under profiles/ (fde, eval)")
    ap.add_argument("--catalog", help="default: the profile's data/checks.json")
    ap.add_argument("--history", help="history.jsonl; its latest audit fills the Last audit columns")
    ap.add_argument("--out", help="default: the profile's references/checks.md")
    a = ap.parse_args()
    pdir = PROFILES / a.profile
    if not (pdir / "profile.json").exists():
        raise SystemExit(f"Unknown profile {a.profile!r}: no {pdir / 'profile.json'}")
    profile = json.loads((pdir / "profile.json").read_text())
    a.catalog = a.catalog or str(pdir / "data" / "checks.json")
    a.out = a.out or str(pdir / "references" / "checks.md")
    cat = json.loads(Path(a.catalog).read_text())
    base, source = {}, "recorded"
    if a.history and Path(a.history).exists():
        lines = [l for l in Path(a.history).read_text().splitlines() if l.strip()]
        if lines:
            base = max((json.loads(l) for l in lines), key=lambda e: e["date"])
    if not base and profile.get("baseline"):
        base, source = json.loads((pdir / profile["baseline"]).read_text()), "of the bundled baseline audit"
    bchecks = base.get("checks", {})

    L = [
        "# Check catalogue",
        "",
        f"Generated from `<skill>/profiles/{a.profile}/data/checks.json` by `<skill>/scripts/render_checks.py --profile {a.profile}`. Edit the JSON, then re-run the script; do not edit this file by hand.",
        "",
        (f"Last audit columns = results {source} on {base['date']}." if base
         else "No audit recorded yet, so the Last audit columns are empty."),
        "",
        "## Rules for IDs",
        "",
        "- IDs are permanent. Never renumber or reuse one; history comparisons depend on them.",
        f"- A new check takes the next free number in its lens (e.g. `PQ-16`) and is added to `<skill>/profiles/{a.profile}/data/checks.json` first.",
        "- A check that no longer applies stays in the catalogue and is recorded as `na` with a reason.",
        "",
        "## Statuses",
        "",
        "- `pass` — meets the pass condition everywhere it applies",
        "- `partial` — meets it in some places or in part (counts as half in the pass rate)",
        "- `fail` — does not meet it; evidence required",
        "- `na` — does not apply yet (e.g. redirects before a restructure); excluded from the pass rate",
        "- `not_checked` — skipped this audit; excluded from the pass rate and listed in the report",
        "",
        "## Verify methods",
        "",
    ]
    for k, v in cat["verify_methods"].items():
        L.append(f"- `{k}` — {v}")
    L.append("")
    L.append("## Contents")
    L.append("")
    for code, lens in cat["lenses"].items():
        L.append(f"- [{code} {lens['name']}](#{code.lower()}-{lens['name'].lower().replace(' ', '-')})")
    L.append("- [Gap register](#gap-register)")
    L.append("")

    for code, lens in cat["lenses"].items():
        L.append(f"## {code} {lens['name']}")
        L.append("")
        L.append(f"Question: {lens['question']}")
        L.append("")
        L.append("| ID | Check | Verify | Pass when | Severity | Dimension | Last audit | Evidence |")
        L.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
        for c in cat["checks"]:
            if c["lens"] != code:
                continue
            b = bchecks.get(c["id"], {})
            L.append(
                f"| {c['id']} | {cell(c['title'])} | {c['verify']} | {cell(c['pass_when'])} | {c['severity']} | "
                f"{c['dimension']} | {b.get('status', '-')} | {cell(b.get('evidence', ''))} |"
            )
        L.append("")

    L.append("## Gap register")
    L.append("")
    L.append("Gaps (C = content, S = structure) and the checks that close them. A gap is closed when all its checks pass.")
    L.append("")
    L.append("| Gap | Title | Checks |")
    L.append("| --- | --- | --- |")
    for gid, g in cat["gaps"].items():
        L.append(f"| {gid} | {cell(g['title'])} | {', '.join(g['checks'])} |")
    L.append("")
    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {a.out} ({len(cat['checks'])} checks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
